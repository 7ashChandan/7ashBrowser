const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('browser', {
  newTab: (spaceId) => ipcRenderer.send('tab:new', spaceId),
  openDuckAI: () => ipcRenderer.send('duck-ai:open'),
  activateTab: (id) => ipcRenderer.send('tab:activate', id),
  closeTab: (id) => ipcRenderer.send('tab:close', id),
  togglePin: (id) => ipcRenderer.send('tab:pin', id),
  navigate: (payload) => ipcRenderer.send('tab:navigate', payload),
  back: () => ipcRenderer.send('nav:back'),
  forward: () => ipcRenderer.send('nav:forward'),
  reload: () => ipcRenderer.send('nav:reload'),
  setPanelOpen: (isOpen) => ipcRenderer.send('panel:state', isOpen),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onZenSidebarHover: (cb) => ipcRenderer.on('zen-sidebar-hover', (_e, isExpanded) => cb(isExpanded)),
  setZenSidebarSurfaceHovered: (isHovered) => ipcRenderer.send('zen-sidebar-surface-hover', isHovered),
  getState: () => ipcRenderer.invoke('state:get'),
  onFocusAddress: (cb) => ipcRenderer.on('focus-address', () => cb()),
  toggleBookmark: (url) => ipcRenderer.send('bookmark:toggle', url),
  clearHistory: () => ipcRenderer.send('history:clear'),
  clearBrowsingData: () => ipcRenderer.invoke('privacy:clear-browsing-data'),
  splitTab: (id) => ipcRenderer.send('tab:split', id),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  chooseBackground: (target) => ipcRenderer.invoke('appearance:choose-background', target),
  clearBackground: (target) => ipcRenderer.invoke('appearance:clear-background', target),
  chooseProfileAvatar: () => ipcRenderer.invoke('profile:choose-avatar'),
  clearProfileAvatar: () => ipcRenderer.invoke('profile:clear-avatar'),
  chooseCustomIcon: () => ipcRenderer.invoke('icons:choose-local'),
  openGemini: () => ipcRenderer.send('gemini:open'),
  openGeminiApiKey: () => ipcRenderer.send('gemini:key:open'),
  saveGeminiApiKey: (apiKey) => ipcRenderer.invoke('ai:save-api-key', apiKey),
  clearGeminiApiKey: () => ipcRenderer.invoke('ai:clear-api-key'),
  hasGeminiApiKey: () => ipcRenderer.invoke('ai:has-api-key'),
  askAboutScreen: (prompt) => ipcRenderer.invoke('ai:ask-about-screen', prompt),
  loadExtension: () => ipcRenderer.invoke('extensions:load'),
  listExtensions: () => ipcRenderer.invoke('extensions:list'),
  openExtensionStore: () => ipcRenderer.send('extension:open-store'),
  isWindows: process.platform === 'win32',
  openDefaultAppsSettings: () => ipcRenderer.invoke('settings:open-default-apps'),
});